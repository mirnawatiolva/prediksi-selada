# print("Dataset berhasil dimuat")

df = pd.read_csv('/content/drive/MyDrive/Colab Notebooks/baru/dataset/data_selada.csv', sep=';')
df.head()

# Bersihkan nama kolom dan hapus kolom Unnamed yang kosong
df.columns = df.columns.str.strip()
df = df.loc[:, ~df.columns.str.contains('^Unnamed')]
print("Kolom setelah pembersihan:", df.columns.tolist())
print(df.head())
