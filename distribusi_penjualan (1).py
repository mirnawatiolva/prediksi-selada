# LIME Explanations
# Inisialisasi LIME Explainer
explainer = lime.lime_tabular.LimeTabularExplainer(
    training_data=X_train.values,
    feature_names=X_train.columns.tolist(),
    class_names=targets, # Gunakan nama target untuk multi-output
    mode='regression'
 )

# Pilih satu instance dari X_test untuk dijelaskan
idx_to_explain = 0
instance_to_explain = X_test.iloc[idx_to_explain].values

print(f"\n--- Penjelasan LIME untuk Instance ke-{idx_to_explain + 1} (Periode {X_test.index[idx_to_explain]}) ---")
print(f"Fitur untuk Instance ini: {X_test.iloc[idx_to_explain].to_dict()}")

# Untuk setiap target, jelaskan prediksi menggunakan Voting Regressor (model gabungan)
for target in targets:
    print(f"\nPenjelasan untuk Target: {target}")
    # Karena predict_fn Lime mengharapkan model single-output, kita akan menggunakan model Voting Regressor yang telah dilatih secara individual untuk setiap target.
    model_to_explain = best_models[f'voting_{target}']

    exp = explainer.explain_instance(
        data_row=instance_to_explain,
        predict_fn=lambda x: model_to_explain.predict(pd.DataFrame(x, columns=X_train.columns)),
        num_features=len(features)
    )
    predicted_val = model_to_explain.predict(pd.DataFrame([instance_to_explain], columns=X_train.columns))[0]
    actual_val = y_test.iloc[idx_to_explain][target]
    print(f"  Prediksi Voting Regressor: {predicted_val:.2f}, Aktual: {actual_val}")
    print("  Kontribusi Fitur:")
    for feature, weight in exp.as_list():
        print(f"    - {feature}: {weight:.2f}")

    # Visualisasi penjelasan LIME
    fig = exp.as_pyplot_figure()
    fig.set_size_inches(10, 6)
    plt.title(f'LIME Explanation for {target} (Actual: {actual_val}, Predicted: {predicted_val:.2f})')
    plt.tight_layout()
    plt.show()

